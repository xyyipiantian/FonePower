function hasCJK(s) {
  return /[一-鿿]/.test(s);
}

function translate(name) {
  let s = name;
  for (const [re, repl] of RULES) {
    s = s.replace(re, repl);
  }
  // 清理：去掉仍含英文字母的残留括号内容（多为未命中术语的补充说明）
  s = s.replace(/\([^()]*[A-Za-z][^()]*\)/g, '');
  // 清理：孤立的 " - " 连接符
  s = s.replace(/\s*-\s*/g, '');
  // 折叠多余空格并去首尾空格
  s = s.replace(/\s+/g, ' ').trim();
  // 去掉中文之间的空格，提升阅读连贯性（保留数字/字母与中文之间的空格）
  s = s.replace(/([一-鿿])\s+([一-鿿])/g, '$1$2');
  return s;
}

function main() {
  const mod = require(SRC);
  const list = mod.EXERCISES || mod;
  const out = {};
  const untranslated = [];
  const overridden = [];

  for (const e of list) {
    const id = e.id;
    let zh;
    if (OVERRIDES[id]) {
      zh = OVERRIDES[id];
      overridden.push(id);
    } else {
      zh = translate(e.name);
    }
    out[id] = zh;
    if (!hasCJK(zh)) {
      untranslated.push({ id, name: e.name, zh });
    }
  }

  fs.writeFileSync(OUT, JSON.stringify(out, null, 0), 'utf8');
  console.log('总条数:', list.length);
  console.log('已写入:', OUT);
  console.log('强制覆盖条数(OVERRIDES):', overridden.length, overridden.join(','));
  console.log('未中文化条数(需核查):', untranslated.length);
  if (untranslated.length) {
    console.log('--- 未中文化样例 ---');
    untranslated.slice(0, 30).forEach(u => console.log(u.id, '|', u.name, '=>', u.zh));
  }
}

main();
